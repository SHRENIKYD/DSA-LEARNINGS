// Focused regression checks for the learning atlas; no browser dependencies.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ctx = { window: {}, localStorage: { getItem() { return null; } } };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(__dirname + '/../src/journey.js', 'utf8'), ctx);
const J = ctx.Journey;
const tracks = J.REGIONS.flatMap(r => r.tracks.map(id => ({ id, short: id.toUpperCase(), title: id + ' lessons', modules: [{ id: id + '01', level: 'B' }, { id: id + '02', level: 'I' }] })));
ctx.window.TRACKS = tracks;
const M = {};
tracks.forEach(t => { M[t.id + '01'] = [1, [0], 0, 0, 0]; M[t.id + '02'] = [1, [0], 0, 0, 0]; });
ctx.window.IM_MODS = M;
const registry = Object.fromEntries(tracks.map(t => [t.id, t]));
const done = { 'dsa01-t0': true };
const stats = J.stats(done);
const html = J.atlasHtml(stats, J.REGIONS[0], registry, null);
assert.equal((html.match(/data-island=/g) || []).length, 6);
assert.match(html, /href="dsa.html#dsa02"/, 'starts at next unfinished module');
assert.match(html, /1 \/ 4 activities/, 'uses actual saved region progress');
assert.match(html, /aria-valuenow="25"/);
assert.equal((html.match(/You are here/g) || []).length, 1);
const resumed = J.atlasHtml(stats, J.REGIONS[0], registry, { track: 'dsa', hash: 'dsa02-t0' });
assert.match(resumed, /href="dsa.html#dsa02-t0"/);
assert.match(resumed, /Continue expedition/);
const buttons = J.REGIONS.map(r => ({ key: r.key, classList: { toggle() {} }, setAttribute() {}, getAttribute() { return r.key; } }));
const detail = { innerHTML: '' }, motion = { setAttribute(k, v) { this[k] = v; } };
let paused = false, listener;
const svg = { pauseAnimations() { paused = true; }, unpauseAnimations() { paused = false; } };
const root = { classList: { toggle() {} }, querySelector(s) { return s === '.atlas-route' ? svg : s === '.atlas-motion' ? motion : detail; }, querySelectorAll() { return buttons; }, addEventListener(k, fn) { listener = fn; } };
ctx.document = { querySelector() { return root; } };
ctx.window.matchMedia = () => ({ matches: false });
J.mountAtlas(stats, registry, null);
assert.equal(paused, false);
listener({ target: { closest(s) { return s === '[data-island]' ? buttons[2] : null; } } });
assert.match(detail.innerHTML, /Design Peaks/);
assert.match(detail.innerHTML, /href="lld.html#lld01"/);
assert.match(J.atlasHtml(stats, J.REGIONS[0], registry, null), /atlas-island selected" data-island="peaks"/, 'selection survives progress redraw');
listener({ target: { closest(s) { return s === '.atlas-motion' ? motion : null; } } });
assert.equal(paused, true);
J.mountAtlas(stats, registry, null);
assert.equal(paused, true, 'pause survives redraw');
ctx.window.matchMedia = () => ({ matches: true });
J.mountAtlas(stats, registry, null);
assert.equal(paused, true);
assert.equal(motion.disabled, true);
assert.equal(motion.textContent, 'Reduced motion enabled');
assert.deepEqual(done, { 'dsa01-t0': true }, 'map selection never writes completion');
console.log('PASS: six regions, real progress, next lesson, resume links, region selection, redraw state, pause and reduced motion');
