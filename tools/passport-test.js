const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ctx = { window: {}, localStorage: { getItem() { return null; } } };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(__dirname + '/../src/journey.js', 'utf8'), ctx);
const J = ctx.Journey;
const empty = J.stampsOf(J.stats({}, {}));
let html = J.stampCollectionHtml(empty);
assert.match(html, /0 of 16 collected/);
assert.match(html, /Your first adventure/);
assert.equal((html.match(/class="pst/g) || []).length, 16);
assert.doesNotMatch(html, /st-q/, 'locked stamps display their destination icon');
assert.match(html, /aria-valuemax="25" aria-valuenow="0"/);
const states = empty.map(x => ({ ...x }));
states[0] = { ...states[0], on: true, have: 1 };
states[1] = { ...states[1], have: 16 };
html = J.stampCollectionHtml(states);
assert.match(html, /1 of 16 collected/);
assert.match(html, /From your collection/);
assert.match(html, /aria-valuemax="25" aria-valuenow="16"/);
assert.match(html, /width:64%/);
assert.match(html, /16 \/ 25/);
assert.equal((html.match(/class="pst on"/g) || []).length, 1);
assert.equal((html.match(/id="stp\d+t"/g) || []).length, 17, 'featured and grid stamps get unique SVG paths');
const escaped = J.stampCollectionHtml([{ on: false, have: 0, st: { key: 'x', name: '<script>', how: '<img>', need: 1, icon: 'ship' } }]);
assert.doesNotMatch(escaped, /<script>|<img>/);
assert.match(escaped, /&lt;script&gt;/);
assert.doesNotThrow(() => J.stampCollectionHtml([]));
console.log('PASS: empty collection, earned feature, all 16 stamps, locked previews, actual progress, unique SVG paths, escaped labels');
